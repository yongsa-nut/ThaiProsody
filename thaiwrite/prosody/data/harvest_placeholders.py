"""Harvest generated source poems for cloze/edit (the placeholder pool).

Generates compose candidates with a strong meter model (gpt-5.5) and keeps only
those that score **exactly 1.0** under the grader's own auto-tokenizer
(`grade_text` on the whitespace-normalized poem). The stored `lines` come from
`parse_poem(to_vrk_lines(...))`, so they are self-consistent with how the grader
tokenizes at eval time, with no hand segmentation. Output: placeholder_poems.py.

These generated poems fill each meter's source-poem pool after the composed,
audit-corpus and public-domain poems (see source_poems.py).

  python thaiwrite/prosody/data/harvest_placeholders.py
"""
from __future__ import annotations

import sys
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

HERE = Path(__file__).resolve().parent              # .../prosody/data
REPO = HERE.parents[2]                              # data -> prosody -> thaiwrite -> repo root
sys.path.insert(0, str(REPO))

from dotenv import load_dotenv                                             # noqa: E402
for _p in HERE.parents:
    if (_p / ".env").exists():
        load_dotenv(_p / ".env"); break

from thaiwrite.prosody.eval.promptlib import (clean_poem, load_prompts,    # noqa: E402
                                              render_prompt, to_vrk_lines, SYSTEM)
from thaiwrite.prosody.eval.providers import make_generator               # noqa: E402
from thaiwrite.prosody.eval.registry import REGISTRY                       # noqa: E402
from thaiwrite.prosody.grader_meter import grade_text, parse_poem         # noqa: E402

# placeholder targets per meter (cloze uses all 4 meters; edit uses โคลง + ฉันท์)
TARGET = {"khlong_si_suphap": 10, "intharawichian_chan_11": 10,
          "klon_paet": 14, "kap_yani_11": 20}
MODEL_KEY = "gpt55-med"
CONCURRENCY = 8
HARVEST_LOG = HERE / "harvest_runs.jsonl"
OUT = HERE / "placeholder_poems.py"


def _eval_rhyme_for(meter_id: str) -> bool:
    return True  # all compose poems are full บท with internal rhyme


def main() -> None:
    spec = REGISTRY[MODEL_KEY]
    gen = make_generator(spec, HARVEST_LOG)
    items = load_prompts(["compose_public", "compose_private"])
    by_meter: dict[str, list[dict]] = defaultdict(list)
    for it in items:
        by_meter[it["meter_id"]].append(it)

    kept: dict[str, list[tuple[str, str]]] = defaultdict(list)   # meter -> [(topic, lines_repr)]
    seen_text: set[str] = set()

    for meter_id, target in TARGET.items():
        pool = by_meter[meter_id]
        budget = min(len(pool), target * 2 + 8)        # cap attempts to limit cost
        attempts = pool[:budget]
        print(f"\n{meter_id}: target {target}, generating {len(attempts)} candidates "
              f"(concurrency {CONCURRENCY}) ...", flush=True)

        def _one(it):
            call = gen.generate("harvest", it["id"], render_prompt(it), SYSTEM, spec.max_tokens)
            return it, call

        results = []
        with ThreadPoolExecutor(max_workers=CONCURRENCY) as ex:
            for fut in as_completed(ex.submit(_one, it) for it in attempts):
                results.append(fut.result())

        for it, call in results:
            if len(kept[meter_id]) >= target:
                break
            if call.error:
                continue
            poem = clean_poem(call.response)
            norm = to_vrk_lines(poem)
            if not norm:
                continue
            if grade_text(norm, meter_id, eval_rhyme=_eval_rhyme_for(meter_id))["score"] != 1.0:
                continue
            if norm in seen_text:
                continue
            seen_text.add(norm)
            lines = parse_poem(norm)                  # tuples, self-consistent w/ grader
            kept[meter_id].append((it.get("topic", ""), repr(tuple(lines))))
        print(f"  kept {len(kept[meter_id])}/{target} at score 1.0", flush=True)

    # write placeholder_poems.py
    lines_out = [
        '"""Generated (placeholder) source poems, auto-harvested.',
        "",
        "Generated by data/harvest_placeholders.py: gpt-5.5 compose outputs that score",
        "EXACTLY 1.0 under the grader's auto-tokenizer; `lines` = parse_poem(to_vrk_lines).",
        "They fill each meter's source-poem pool after the composed, audit-corpus and",
        "public-domain poems (see source_poems.py).",
        '"""',
        "from __future__ import annotations",
        "",
        "from thaiwrite.prosody.data.audit_poems import Poem",
        "",
        "PLACEHOLDER_POEMS: tuple[Poem, ...] = (",
    ]
    n = 0
    for meter_id, entries in kept.items():
        lines_out.append(f"    # --- {meter_id} ({len(entries)}) ---")
        for topic, lines_repr in entries:
            n += 1
            src = f"PLACEHOLDER (gpt-5.5) — {topic}"
            lines_out.append(f"    Poem(meter_id={meter_id!r}, source={src!r},")
            lines_out.append(f"         lines={lines_repr}),")
    lines_out.append(")")
    OUT.write_text("\n".join(lines_out) + "\n", encoding="utf-8")
    print(f"\nWrote {n} placeholder poems → {OUT.name}")
    print("by meter:", {m: len(v) for m, v in kept.items()})


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8")
    main()
